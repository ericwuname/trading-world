"""MCP 交易工具——需 ``TW_MCP_ALLOW_TRADE=1``，且**当前未实现**。

为什么这里是空的（这不是占位符，是决定）
----------------------------------------
把「下单」做成一个 MCP 工具在技术上一行就能写完，但那会把一个
**高风险能力**混进一个「顺手就能开」的开关里。所以刻意不实现：

============================  ==================================================
阶段                            下单该走哪条路
============================  ==================================================
A 路线（模拟，当前）           项目内部的执行器（``tw/`` 里的订单模型 + 账本）。
                              外部 Agent 通过 MCP 下单**没有需求**——
                              模拟盘的对手方是本项目的引擎，不是外部调用方。
B 路线（真钱，后置）           需要**单独一轮**设计与评审：
                              · 独立进程 + 独立 token（不与只读服务共存）
                              · 单笔上限 + 日累计上限 + 冷却期
                              · 人工确认开关（GUI 上一个实体按钮）
                              · 先跑通「模拟 → 影子模式（真实行情、假下单）
                                → 极小额度真实单」三级放行
                              在此之前，**不注册任何下单工具**。
============================  ==================================================

⚠️ 谁要是想绕过这里直接加 ``place_order``，请先回答：
**如果这个工具被误调用一次，损失上限是多少？** 答不上来就不该加。
"""

from __future__ import annotations

from typing import Any


def register(mcp: Any) -> None:  # noqa: ANN001
    """注册交易类工具。**目前只注册"查询"级别的能力，不含下单。**

    实际上连查询也不注册——A 路线的账户在项目进程内存里，
    MCP 服务是另一个进程，看不到它。
    等 A1（订单模型 + 账户账本）落地并有持久化后，再把只读的
    ``get_positions`` / ``get_orders`` 加到这里。
    """
    raise RuntimeError(
        "交易类 MCP 工具尚未实现。这是**有意的**：\n"
        "  · A 路线（模拟）下，下单由项目内部执行器完成，不需要 MCP；\n"
        "  · B 路线（真钱）需要单独一轮设计与评审（独立进程/额度上限/"
        "人工确认/三级放行），不是顺手加个函数的事。\n"
        "详见本模块的 docstring。"
    )


__all__ = ["register"]
