"""打包时随包带上的数据 —— **唯一定义点**。

为什么单独一个模块
------------------
两边都要用这份清单，而两边都不能去 import `gui.api_doc`
（它拉 numpy / tw，代价大，且会在**构建期**把项目依赖引进来）：
  · `packaging/trading_world.spec` —— PyInstaller 打包时读它；
  · `tests/test_gui.py` —— 对照 `api_doc.DOC_REPORTS` 检查**覆盖率**。
所以清单住在这个**零依赖**模块里（只有两个元组 + 一个纯函数）。

⭐ 划线的依据：**用户在安装包里点开每一个标签页，都该看到内容**
----------------------------------------------------------------
清单覆盖 = 界面上**八**个页面各自的数据源：

| 页面 | 靠什么在包里 |
|---|---|
| 总览 / 图表 / 指标 / 策略表现 / 对照 | `out/` 里的 JSON 由作业**现跑现写**到内存，不需要随包 |
| 真实比对 | `data/`（真实行情） |
| **文档验证** | `out/a14` `out/a15` `out/a16` + 三份 `docs/A1x-*.md` |
| **Agent 决策** | `out/a4` `out/a5` `docs/llm-run-*`（**运行产物**） |

⚠️ **2026-09-28 的决定改过一次，两次都写在这里**：
第一版把 `out/a4|a5`、`docs/llm-run-*` 判为"运行产物、不打"，
理由是"全新安装里没有它们是正常的，前端有空状态"。
用户明确要求「运行产物也打进包」后改成**打** —— 代价 ~31 MB
（157 MB → 188 MB），换来的是**八个页面全都不是空的**。
⭐ 教训：**"某页空着也算正常"这种判断是产品决定，不是技术决定**，
该交给人拍板；技术侧要做的是把代价算清楚（+31 MB）并留一行开关。

⚠️ 漏掉一项的后果**不是报错**，而是那个功能在安装包里**静默失效**：
实测踩到（2026-09-28）第一版只带了 `data/` 与 `gui/static`，
`out/a14|a15|a16` 三份结果 JSON 没进包 ⇒「文档验证」页在安装包里
永远显示"产物缺失"，而开发机上一切正常（那里 `out/` 就在手边）。
⇒ 所以有 `covers()` + 测试：清单必须覆盖界面会读的每一个文件
（包括 `agent_api.RUN_DIRS` 里那四个"扫描目录"）。
"""

from __future__ import annotations

#: 整个目录随包带上（相对项目根，正斜杠）
BUNDLE_DIRS: tuple[str, ...] = (
    "data",           # 真实行情：tw/realdata.py 靠相对位置找它
    "gui/static",     # 前端单文件：gui/server.py 靠相对位置找它
    "out/a14",        # ⭐ 文档验证页的数据源（缺了那页就是死的）
    "out/a15",
    "out/a16",
    "out/a4",         # ⭐ Agent 决策页：可浏览的运行（A4 执行模拟的留痕）
    "out/a5",         # ⭐ Agent 决策页：可浏览的运行（A5 留痕，约 26 MB）
    "docs/llm-run-20260921-a4",   # ⭐ Agent 决策页的另外两个扫描目录
    "docs/llm-run-20260921",
)

#: 单个文件随包带上（相对项目根，正斜杠）。
#: ⚠️ 这三份与 `gui/api_doc.py::DOC_REPORTS` 里的报告文件是同一批 ——
#: 故意留成"两处写、一处测"：测试会发现脱节（见 `test_打包清单覆盖…`）。
BUNDLE_FILES: tuple[str, ...] = (
    "docs/A14-个人交易决策系统方案-验证报告.md",
    "docs/A15-右尾策略完全手册-验证报告.md",
    "docs/A16-两文档策略接入系统-实测报告.md",
)


def covers(rel: str) -> bool:
    """相对项目根的路径 ``rel`` 会不会随包带上。"""
    p = rel.replace("\\", "/").lstrip("/")
    return p in BUNDLE_FILES or any(
        p == d or p.startswith(d + "/") for d in BUNDLE_DIRS
    )


__all__ = ["BUNDLE_DIRS", "BUNDLE_FILES", "covers"]
